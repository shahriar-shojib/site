import type { Marks } from './marks'
import type { Rgb } from './math'
import { BLOOM, GREEN, OWL_EYE, PAPER, RIM, SOOT } from './palette'

interface Ink {
  rgb: Rgb
  ink: number
}

const ink = (rgb: Rgb, amount = 1): Ink => ({ rgb, ink: amount })

// One character per cell; '.' is empty. White is bare paper, so it only reads where something darker borders it.
const INKS: Record<string, Ink> = {
  k: ink(SOOT),
  K: ink([58, 50, 46]),
  p: ink([118, 66, 112]),
  U: ink([112, 98, 88]),
  w: ink(PAPER, 0),
  S: ink([156, 168, 204]),
  m: ink(RIM),
  g: ink(GREEN),
  G: ink([110, 214, 120]),
  d: ink([10, 70, 56]),
  r: ink(BLOOM),
  e: ink([92, 104, 148]),
  E: ink([214, 220, 236], 0.8),
  o: ink([238, 148, 60]),
  s: ink([150, 160, 184], 0.55),
  b: ink([128, 92, 62], 0.7),
  B: ink([84, 58, 38], 0.9),
  c: ink([226, 212, 176], 0.9),
  l: ink([170, 140, 104], 0.9),
  y: ink(OWL_EYE),
  n: ink([156, 122, 94]),
  N: ink([104, 80, 62]),
  P: ink([242, 150, 160]),
}
const KEYS = Object.keys(INKS)
const PALETTE = Object.values(INKS)

export interface Sprite {
  w: number
  h: number
  /** Rows that hang below the anchor, like a tail under a perch. */
  below: number
  /** One palette index per cell, 1-based; 0 is empty. */
  cells: Uint8Array
}

/** Parses pixel art drawn facing right. */
export function sprite(art: string, below = 0): Sprite {
  const rows = art.trim().split('\n').map((row) => row.trim())
  const cells = Uint8Array.from(rows.join(''), (ch) => KEYS.indexOf(ch) + 1)
  return { w: rows[0].length, h: rows.length, below, cells }
}

/** Draws a sprite one pixel per cell with its bottom centre at (x, y); `dir` -1 mirrors it to face left. */
export function drawSprite(marks: Marks, s: Sprite, x: number, y: number, dir: number, alpha: number) {
  const { pitch } = marks.grid
  const c0 = Math.round(x / pitch - s.w / 2)
  const r0 = Math.round(y / pitch) - s.h + s.below
  for (let row = 0; row < s.h; row++) {
    for (let col = 0; col < s.w; col++) {
      const m = s.cells[row * s.w + (dir < 0 ? s.w - 1 - col : col)]
      if (!m) continue
      const { rgb, ink } = PALETTE[m - 1]
      marks.cell(c0 + col, r0 + row, rgb, ink, alpha)
    }
  }
}

/** Stacks pixel art of the same size; later layers cover earlier ones wherever they are not '.'. */
function layer(...arts: string[]) {
  const grids = arts.map((art) => art.trim().split('\n').map((row) => row.trim()))
  return grids[0]
    .map((row, y) => [...row].map((ch, x) => grids.reduce((at, g) => (g[y][x] !== '.' ? g[y][x] : at), ch)).join(''))
    .join('\n')
}

